import { Download, Image as ImageIcon, Loader2, RefreshCw, Sparkles } from 'lucide-react';
import { useEffect, useState } from 'react';
import { GeneratedArtwork } from '../types';

interface GeneratedArtworkCardProps {
  artwork: GeneratedArtwork;
  isRegenerating?: boolean;
  onQuickEditHint?: (artwork: GeneratedArtwork) => void;
  onRegenerate?: (artwork: GeneratedArtwork) => void;
}

function dataUrlToLosslessBlob(dataUrl: string): { blob: Blob; ext: string } | null {
  try {
    const commaIdx = dataUrl.indexOf(',');
    if (commaIdx < 0) return null;
    const header = dataUrl.slice(5, commaIdx);
    const mime = header.split(';')[0] || 'image/png';
    const base64 = dataUrl.slice(commaIdx + 1);
    const binary = atob(base64);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
      bytes[i] = binary.charCodeAt(i);
    }
    const ext = mime.includes('webp')
      ? 'webp'
      : mime.includes('jpeg') || mime.includes('jpg')
        ? 'jpg'
        : 'png';
    return { blob: new Blob([bytes], { type: mime }), ext };
  } catch {
    return null;
  }
}

const FREE_POLLINATIONS_MODELS = ['flux', 'flux-realism', 'flux-3d', 'turbo'] as const;

export function GeneratedArtworkCard({
  artwork,
  isRegenerating = false,
  onQuickEditHint,
  onRegenerate,
}: GeneratedArtworkCardProps) {
  const rawSourceUrl = artwork.imageUrl || '';

  const [activeSrc, setActiveSrc] = useState(rawSourceUrl);
  const [fallbackIdx, setFallbackIdx] = useState(0);
  const [imgLoading, setImgLoading] = useState(Boolean(rawSourceUrl));
  const [imgFailed, setImgFailed] = useState(false);
  const [naturalDims, setNaturalDims] = useState<{ w: number; h: number } | null>(null);

  useEffect(() => {
    setActiveSrc(rawSourceUrl);
    setFallbackIdx(0);
    setImgFailed(false);
    setImgLoading(Boolean(rawSourceUrl));
  }, [rawSourceUrl]);

  const tryNextFreeModelUrl = (currentIdx: number) => {
    const promptForUrl = (artwork.detailedPrompt || artwork.title || '').trim();
    if (!promptForUrl || currentIdx >= FREE_POLLINATIONS_MODELS.length) {
      setImgLoading(false);
      setImgFailed(true);
      return;
    }
    const nextModel = FREE_POLLINATIONS_MODELS[currentIdx];
    const w = artwork.width || 1024;
    const h = artwork.height || 1024;
    const seed = Math.floor(Math.random() * 1_000_000_000) + 1;
    const nextUrl = `https://pollinations.ai/p/${encodeURIComponent(promptForUrl)}?width=${w}&height=${h}&nologo=true&enhance=true&seed=${seed}&model=${nextModel}`;
    setFallbackIdx(currentIdx + 1);
    setActiveSrc(nextUrl);
    setImgLoading(true);
    setImgFailed(false);
  };

  // Automatic 12-second timeout failover for remote image URLs
  useEffect(() => {
    if (!imgLoading || !activeSrc || activeSrc.startsWith('data:')) return;
    const timer = setTimeout(() => {
      tryNextFreeModelUrl(fallbackIdx === 0 ? 1 : fallbackIdx);
    }, 12000);
    return () => clearTimeout(timer);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [imgLoading, activeSrc, fallbackIdx]);

  const engineLabel =
    artwork.provider === 'imagen' || artwork.modelUsed?.includes('imagen')
      ? 'Google Gemini Imagen 3 HD'
      : artwork.provider === 'flux-hd'
        ? 'Roosters AI Studio (FLUX.1 HD)'
        : artwork.provider === 'ai-horde'
          ? 'Roosters AI Studio (Horde HD)'
          : artwork.provider === 'airforce'
            ? 'Roosters AI Studio (FLUX HD)'
            : artwork.provider === 'pollinations'
              ? `Roosters AI Studio (${(artwork.modelUsed || 'flux').toUpperCase()} HD)`
              : artwork.provider === 'nano-banana'
                ? artwork.modelUsed?.includes('3.1')
                  ? 'Nano Banana (3.1 Preview)'
                  : 'Gemini Native Image HD'
                : artwork.provider === 'svg'
                  ? 'Vector Art'
                  : 'Generated by Roosters AI HD';

  const hasRaster = Boolean(activeSrc) && !imgFailed;
  const hasSvg = Boolean(artwork.svgCode);
  const svgDataUrl = artwork.svgCode
    ? `data:image/svg+xml;charset=utf-8,${encodeURIComponent(artwork.svgCode)}`
    : '';
  const safeFileSlug =
    artwork.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 48) || 'roosters-hd-image';

  const displayWidth = naturalDims?.w || artwork.width;
  const displayHeight = naturalDims?.h || artwork.height;

  const handleDownloadSvg = () => {
    if (!artwork.svgCode) return;
    const blob = new Blob([artwork.svgCode], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${safeFileSlug}.svg`;
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
  };

  const handleDownloadHD = async () => {
    if (hasRaster && activeSrc) {
      if (activeSrc.startsWith('data:')) {
        const raw = dataUrlToLosslessBlob(activeSrc);
        if (raw) {
          const url = URL.createObjectURL(raw.blob);
          const link = document.createElement('a');
          link.href = url;
          link.download = `${safeFileSlug}-hd.${raw.ext}`;
          document.body.appendChild(link);
          link.click();
          link.remove();
          URL.revokeObjectURL(url);
          return;
        }
      }

      try {
        const resp = await fetch(activeSrc);
        if (resp.ok) {
          const blob = await resp.blob();
          const mime = blob.type || 'image/png';
          const ext = mime.includes('webp') ? 'webp' : mime.includes('jpeg') ? 'jpg' : 'png';
          const url = URL.createObjectURL(blob);
          const link = document.createElement('a');
          link.href = url;
          link.download = `${safeFileSlug}-hd.${ext}`;
          document.body.appendChild(link);
          link.click();
          link.remove();
          URL.revokeObjectURL(url);
          return;
        }
      } catch {
        // Fallback to direct anchor
      }
      const link = document.createElement('a');
      link.href = activeSrc;
      link.download = `${safeFileSlug}-hd.png`;
      link.target = '_blank';
      link.rel = 'noopener noreferrer';
      document.body.appendChild(link);
      link.click();
      link.remove();
      return;
    }

    if (!artwork.svgCode) return;
    const img = new Image();
    const blob = new Blob([artwork.svgCode], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    img.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = artwork.width || 1024;
      canvas.height = artwork.height || 1024;
      const ctx = canvas.getContext('2d');
      if (ctx) {
        ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
        canvas.toBlob((pngBlob) => {
          if (!pngBlob) return;
          const pngUrl = URL.createObjectURL(pngBlob);
          const link = document.createElement('a');
          link.href = pngUrl;
          link.download = `${safeFileSlug}-hd.png`;
          document.body.appendChild(link);
          link.click();
          link.remove();
          URL.revokeObjectURL(pngUrl);
        }, 'image/png');
      }
      URL.revokeObjectURL(url);
    };
    img.src = url;
  };

  return (
    <div className="mt-3 rounded-xl border border-[#1f293d] bg-[#090b10] overflow-hidden shadow-lg">
      {/* Dark Frame Header */}
      <div className="flex flex-wrap items-center justify-between gap-2.5 px-3.5 py-2.5 border-b border-[#1f293d] bg-[#0f1420]">
        <div className="flex items-center gap-2 min-w-0">
          <ImageIcon className="w-4 h-4 text-[#ffd700] shrink-0" />
          <span className="text-[13px] font-semibold text-white truncate">{artwork.title}</span>
          <span className="text-[11px] text-[#64748b] tabular-nums shrink-0">
            {displayWidth}×{displayHeight} HD
          </span>
        </div>

        <div className="flex items-center gap-2 shrink-0">
          {hasRaster && onQuickEditHint && (
            <button
              type="button"
              onClick={() => onQuickEditHint(artwork)}
              className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg bg-[#182032] border border-[#334155] text-[11.5px] font-medium text-[#ffd700] hover:border-[#ffd700] transition-colors cursor-pointer whitespace-nowrap"
            >
              <Sparkles className="w-3 h-3" />
              <span>Edit</span>
            </button>
          )}
          {hasSvg && !hasRaster && (
            <button
              type="button"
              onClick={handleDownloadSvg}
              className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-lg bg-[#182032] border border-[#334155] text-[11.5px] font-medium text-slate-200 hover:border-[#ffd700] hover:text-[#ffd700] transition-colors cursor-pointer whitespace-nowrap"
            >
              <Download className="w-3.5 h-3.5" />
              <span>SVG</span>
            </button>
          )}
        </div>
      </div>

      {/* Clean Dark Image Frame */}
      <div className="relative p-3 flex items-center justify-center bg-[#06080d] min-h-[260px]">
        {(imgLoading || isRegenerating) && (
          <div
            className={`w-full rounded-lg border border-[#1f293d] bg-gradient-to-br from-[#0f1626] via-[#172136] to-[#0a0e18] animate-pulse flex flex-col items-center justify-center gap-3 text-center px-4 py-10 ${
              artwork.aspectRatio === '16:9'
                ? 'aspect-video'
                : artwork.aspectRatio === '9:16'
                  ? 'aspect-[9/16] max-w-[300px] mx-auto'
                  : artwork.aspectRatio === '4:3'
                    ? 'aspect-[4/3] max-w-[520px] mx-auto'
                    : 'aspect-square max-w-[420px] mx-auto'
            }`}
          >
            <div className="w-11 h-11 rounded-full border-2 border-[#00d4ff]/30 border-t-[#ffd700] animate-spin" />
            <div>
              <p className="text-[13.5px] font-semibold text-white">
                {isRegenerating
                  ? `Regenerating ${displayWidth}×${displayHeight} HD Image...`
                  : `Rendering ${displayWidth}×${displayHeight} HD AI Image...`}
              </p>
              <p className="text-[11.5px] text-[#94a3b8] mt-1">
                {fallbackIdx > 0
                  ? `Switching seamlessly to free engine (${FREE_POLLINATIONS_MODELS[Math.min(fallbackIdx - 1, FREE_POLLINATIONS_MODELS.length - 1)].toUpperCase()})`
                  : `${engineLabel} synthesis in progress`}
              </p>
            </div>
          </div>
        )}

        {hasRaster ? (
          <div
            className={`rounded-lg border border-[#1f293d] overflow-hidden bg-[#05070c] ${
              imgLoading || isRegenerating ? 'hidden' : 'block'
            }`}
          >
            <img
              src={activeSrc}
              alt={artwork.title}
              referrerPolicy="no-referrer"
              onLoad={(e) => {
                const nw = e.currentTarget.naturalWidth;
                const nh = e.currentTarget.naturalHeight;
                if (nw > 0 && nh > 0) {
                  setNaturalDims({ w: nw, h: nh });
                }
                setImgLoading(false);
                setImgFailed(false);
              }}
              onError={() => {
                if (!activeSrc.startsWith('data:') && fallbackIdx < FREE_POLLINATIONS_MODELS.length) {
                  tryNextFreeModelUrl(fallbackIdx === 0 ? 1 : fallbackIdx);
                  return;
                }
                setImgLoading(false);
                setImgFailed(true);
              }}
              className={`max-h-[540px] w-auto object-contain transition-opacity duration-300 ${
                imgLoading ? 'opacity-0' : 'opacity-100'
              }`}
            />
          </div>
        ) : hasSvg ? (
          <img
            src={svgDataUrl}
            alt={artwork.title}
            referrerPolicy="no-referrer"
            className="max-h-[420px] w-auto rounded-lg object-contain border border-[#1f293d]"
          />
        ) : (
          <div className="w-full py-12 rounded-lg border border-[#1f293d] bg-gradient-to-br from-[#111622] to-[#090b10] flex flex-col items-center justify-center gap-3 text-center px-4">
            <ImageIcon className="w-8 h-8 text-[#00d4ff]" />
            <div>
              <span className="text-[13.5px] font-semibold text-white block">{artwork.title}</span>
              <span className="text-[12px] text-[#94a3b8]">
                Image preview could not be loaded. Tap Regenerate to render a fresh HD image.
              </span>
            </div>
            {onRegenerate && (
              <button
                type="button"
                onClick={() => onRegenerate(artwork)}
                disabled={isRegenerating}
                className="inline-flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg bg-[#182032] border border-[#334155] text-[12px] font-semibold text-[#00d4ff] hover:border-[#00d4ff] disabled:opacity-50 cursor-pointer"
              >
                <RefreshCw className={`w-3.5 h-3.5 ${isRegenerating ? 'animate-spin' : ''}`} />
                <span>Regenerate</span>
              </button>
            )}
          </div>
        )}
      </div>

      {/* Underneath Image: Prompt Summary + One-Click Download HD & Regenerate Buttons */}
      <div className="px-3.5 py-3 border-t border-[#1f293d] bg-[#0b0f18] space-y-2.5">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <div className="min-w-0 flex-1">
            {artwork.description && (
              <p dir="auto" className="text-[12px] text-[#94a3b8] line-clamp-2">
                {artwork.description}
              </p>
            )}
          </div>
          {imgLoading || isRegenerating ? (
            <span className="inline-flex items-center gap-1 text-[11px] text-[#00d4ff] shrink-0">
              <Loader2 className="w-3 h-3 animate-spin" />
              <span>{engineLabel}</span>
            </span>
          ) : (
            <span className="text-[11px] text-[#64748b] shrink-0 whitespace-nowrap">
              {artwork.isEdited ? `${engineLabel} · Edited` : engineLabel}
            </span>
          )}
        </div>

        {(hasRaster || hasSvg) && (
          <div className="flex flex-wrap items-center gap-2 pt-0.5">
            <button
              type="button"
              onClick={handleDownloadHD}
              disabled={imgLoading || isRegenerating}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-gradient-to-r from-[#ffd700] to-[#f59e0b] text-[#050608] text-[12px] font-bold hover:brightness-110 disabled:opacity-50 transition-all cursor-pointer whitespace-nowrap shadow-sm"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download HD</span>
            </button>

            {onRegenerate && (
              <button
                type="button"
                onClick={() => onRegenerate(artwork)}
                disabled={imgLoading || isRegenerating}
                className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-[#182032] border border-[#334155] text-[12px] font-semibold text-[#00d4ff] hover:border-[#00d4ff] hover:bg-[#1e293b] disabled:opacity-50 transition-colors cursor-pointer whitespace-nowrap"
              >
                <RefreshCw
                  className={`w-3.5 h-3.5 ${imgLoading || isRegenerating ? 'animate-spin' : ''}`}
                />
                <span>Regenerate</span>
              </button>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
